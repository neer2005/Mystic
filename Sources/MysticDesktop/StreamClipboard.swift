import AppKit
import UniformTypeIdentifiers
import MysticKit

@MainActor
protocol StreamPasteboard: AnyObject {
    var changeCount: Int { get }
    var protectsContent: Bool { get }
    func text(limit: Int) throws -> String?
    func write(_ text: String) throws
}

@MainActor
final class MacStreamPasteboard: StreamPasteboard {
    private let pasteboard: NSPasteboard
    init(_ pasteboard: NSPasteboard = .general) { self.pasteboard=pasteboard }
    var changeCount: Int { pasteboard.changeCount }
    var protectsContent: Bool {
        let types=pasteboard.types ?? []
        if !types.isEmpty,!types.contains(.string) { return true }
        return types.contains { type in
            type == .fileURL || type.rawValue == "NSFilenamesPboardType"
                || type.rawValue.hasPrefix("com.apple.filepromise")
                || ["org.nspasteboard.ConcealedType","org.nspasteboard.TransientType","org.nspasteboard.AutoGeneratedType"].contains(type.rawValue)
                || UTType(type.rawValue)?.conforms(to:.image) == true
        }
    }
    func text(limit: Int) throws -> String? {
        guard !protectsContent,let text=pasteboard.string(forType:.string) else { return nil }
        try ClipboardText.validate(text,limit:limit)
        return text
    }
    func write(_ text: String) throws {
        try ClipboardText.validate(text,limit:ClipboardText.manualLimit)
        if !protectsContent,pasteboard.string(forType:.string) == text { return }
        let item=NSPasteboardItem()
        guard item.setString(text,forType:.string) else { throw HostConnectionError("Clipboard text could not be prepared.") }
        pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else { throw HostConnectionError("The Mac clipboard changed before text could be written.") }
    }
}

/// One stream's clipboard work. All system-clipboard access belongs to the main actor.
@MainActor
final class StreamClipboard {
    typealias Step = @Sendable (Bool,Bool,String?) async throws -> ClipboardSyncResult
    let canRead: Bool
    let canSend: Bool
    private let host: any HostService
    private let pasteboard: any StreamPasteboard
    private let isActive: () -> Bool
    private let step: Step
    private let report: (String,Bool) -> Void
    private let syncEnabled: Bool
    private var monitor: Task<Void,Never>?
    private var manual: Task<Void,Never>?
    private var observers: [NSObjectProtocol]=[]
    private var stopped=false
    private var syncAvailable: Bool?
    private var lastChangeCount: Int?
    private var blockedChangeCount: Int?
    private var needsBaseline=true
    private var activityRevision: UInt64=0
    private var status="Clipboard ready"
    private var reportedBusy=false

    init(host: any HostService,pasteboard: any StreamPasteboard = MacStreamPasteboard(),
         canRead: Bool,canSend: Bool,syncEnabled: Bool,isActive: @escaping () -> Bool,
         step: @escaping Step,report: @escaping (String,Bool) -> Void,observeFocus: Bool = true) {
        self.host=host;self.pasteboard=pasteboard;self.canRead=canRead;self.canSend=canSend
        self.syncEnabled=syncEnabled;self.isActive=isActive;self.step=step;self.report=report
        if observeFocus {
            for name in [NSApplication.didResignActiveNotification,NSWindow.didResignKeyNotification] {
                observers.append(NotificationCenter.default.addObserver(forName:name,object:nil,queue:.main) { [weak self] _ in
                    MainActor.assumeIsolated { self?.invalidateFocus() }
                })
            }
        }
    }
    isolated deinit { stop() }
    func start() {
        guard canRead || canSend else { publish("This host does not allow clipboard text sharing.");return }
        publish(syncEnabled ? "Clipboard sync waiting for the stream window" : "Clipboard text sharing ready")
        guard syncEnabled,canRead || canSend else { return }
        monitor=Task { [weak self] in
            while !Task.isCancelled {
                guard let self,!self.stopped else { return }
                await self.poll()
                do { try await Task.sleep(for:.milliseconds(250)) } catch { return }
            }
        }
    }
    func stop() {
        guard !stopped else { return };stopped=true;activityRevision &+= 1
        monitor?.cancel();monitor=nil;manual?.cancel();manual=nil
        for observer in observers { NotificationCenter.default.removeObserver(observer) };observers=[]
    }
    func invalidateFocus() { activityRevision &+= 1;needsBaseline=true;lastChangeCount=nil }
    private func publish(_ text: String,busy: Bool = false) {
        guard !stopped else { return }
        if status != text || reportedBusy != busy { status=text;reportedBusy=busy;report(text,busy) }
    }
    func sendTextToHost() {
        guard !stopped,manual == nil,canSend,isActive() else { return }
        do {
            guard let text=try pasteboard.text(limit:ClipboardText.manualLimit) else {
                publish("Copy plain text first. Files, images and protected clipboard items stay on this Mac.");return
            }
            publish("Sending clipboard text…",busy:true)
            manual=Task { [weak self] in
                guard let self else { return }
                defer { self.manual=nil }
                do {
                    try await self.host.sendClipboardText(text)
                    guard !self.stopped,!Task.isCancelled else { return }
                    self.needsBaseline=true
                    self.publish("Clipboard text sent to host")
                } catch { self.publish("Clipboard transfer failed: \(error.localizedDescription)") }
            }
        } catch { publish(error.localizedDescription) }
    }
    func copyTextFromHost() {
        guard !stopped,manual == nil,canRead,isActive() else { return }
        let count=pasteboard.changeCount,revision=activityRevision
        publish("Reading host clipboard…",busy:true)
        manual=Task { [weak self] in
            guard let self else { return }
            defer { self.manual=nil }
            do {
                let text=try await self.host.clipboardText()
                guard !self.stopped,!Task.isCancelled else { return }
                try ClipboardText.validate(text,limit:ClipboardText.manualLimit)
                guard self.isActive(),self.activityRevision == revision,self.pasteboard.changeCount == count else {
                    self.publish("Host text was not copied because the Mac clipboard or active window changed.");return
                }
                try self.pasteboard.write(text)
                self.needsBaseline=true
                self.publish("Host text copied to Mac clipboard")
            } catch { self.publish("Clipboard transfer failed: \(error.localizedDescription)") }
        }
    }
    /// Awaited polling bounds in-flight work. No clipboard contents are read while inactive/off.
    func poll() async {
        guard !stopped,syncEnabled,manual == nil,syncAvailable != false else { return }
        do {
            if syncAvailable == nil {
                let result=try await step(false,true,nil)
                guard !stopped,!Task.isCancelled else { return }
                syncAvailable=result.available
                guard result.available else { publish("Automatic clipboard sync is unavailable on this host. Manual text transfers are still available.");return }
            }
            guard isActive() else {
                invalidateFocus()
                _=try await step(false,false,nil)
                publish("Clipboard sync paused outside the stream window");return
            }
            let count=pasteboard.changeCount,revision=activityRevision
            if blockedChangeCount != count { blockedChangeCount=nil }
            let baseline=needsBaseline
            var local: String?
            var keepLocal=pasteboard.protectsContent || blockedChangeCount == count
            var localIssue: String?
            if canSend,!keepLocal,baseline || lastChangeCount != count {
                do { local=try pasteboard.text(limit:ClipboardText.syncLimit) }
                catch { keepLocal=true;blockedChangeCount=count;localIssue="This copy cannot sync automatically. Use Send Text to Host for text up to 1 MiB." }
            }
            let result=try await step(true,baseline,local)
            guard !stopped,!Task.isCancelled else { return }
            guard isActive(),revision == activityRevision,manual == nil else { needsBaseline=true;return }
            needsBaseline=false;lastChangeCount=count
            if let text=result.text,canRead {
                guard !(local != nil && !baseline),!keepLocal,!pasteboard.protectsContent,pasteboard.changeCount == count else {
                    publish("Clipboard sync kept the newer or non-text Mac clipboard item.");return
                }
                try ClipboardText.validate(text,limit:ClipboardText.syncLimit)
                try pasteboard.write(text)
                // Do not mistake our own write for a newer local copy if another host copy arrives.
                lastChangeCount=pasteboard.changeCount
            }
            publish(localIssue ?? (keepLocal ? "Clipboard sync keeps this local clipboard item on the Mac" : "Clipboard text sync active"))
        } catch {
            guard !stopped else { return }
            syncAvailable=false
            _=try? await step(false,false,nil)
            publish("Clipboard sync stopped: \(error.localizedDescription)")
        }
    }
}
